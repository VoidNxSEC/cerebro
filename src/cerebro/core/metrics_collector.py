    def _collect_delivery(self, repo_path: Path, snapshot: RepoMetricsSnapshot) -> None:
        """Sustained delivery: how much of the repo's life had real work in it.

        Replaces raw recency. A repo with 12,744 commits spread over years is a
        sustained platform investment; the old activity term scored it 0 for not
        having been touched in the last 30 days.
        """
        months = self._git_output(repo_path, ["log", "--format=%ad", "--date=format:%Y-%m"])
        stamps = [m for m in months.split("\n") if m.strip()]
        if not stamps:
            snapshot.delivery = {"score": 0.0, "active_months": 0, "lifespan_months": 0}
            return

        active = sorted(set(stamps))
        first, last = active[0], active[-1]
        fy, fm = (int(x) for x in first.split("-"))
        ly, lm = (int(x) for x in last.split("-"))
        lifespan = max(1, (ly - fy) * 12 + (lm - fm) + 1)
        consistency = len(active) / lifespan

        score = min(60.0, consistency * 60.0)          # rhythm
        score += min(25.0, len(active) * 1.2)          # accumulated months of work
        score += min(15.0, len(stamps) / 100.0)        # raw volume, heavily damped

        snapshot.delivery = {
            "score": round(min(100.0, score), 1),
            "active_months": len(active),
            "lifespan_months": lifespan,
            "consistency": round(consistency, 3),
            "first_commit_month": first,
            "last_commit_month": last,
        }

    def _collect_release(self, repo_path: Path, snapshot: RepoMetricsSnapshot) -> None:
        tags = self._git_output(repo_path, ["tag", "--list"]).split()
        semver = [t for t in tags if re.match(r"^v?\d+\.\d+\.\d+", t)]
        changelog = any((repo_path / n).exists() for n in ("CHANGELOG.md", "CHANGELOG", "CHANGES.md"))
        wf_dir = repo_path / ".github" / "workflows"
        release_wf = wf_dir.is_dir() and any("release" in p.name.lower() for p in wf_dir.glob("*.y*ml"))

        score = 0.0
        score += min(40.0, len(tags) * 8.0)
        if semver:
            score += 25.0
        if changelog:
            score += 20.0
        if release_wf:
            score += 15.0

        snapshot.release = {
            "score": round(min(100.0, score), 1),
            "tags": len(tags),
            "semver_tags": len(semver),
            "has_changelog": changelog,
            "has_release_workflow": release_wf,
        }

    def _collect_reproducibility(self, repo_path: Path, snapshot: RepoMetricsSnapshot) -> None:
        """Depth of the build contract, not merely `flake.nix exists`.

        32 of 33 repos here ship a flake; as a boolean that fact carries one bit and
        the ecosystem's single strongest differentiator disappears into it.
        """
        flake = repo_path / "flake.nix"
        if not flake.exists():
            lock = any((repo_path / n).exists() for n in
                       ("package-lock.json", "pnpm-lock.yaml", "Cargo.lock", "poetry.lock", "uv.lock"))
            snapshot.reproducibility = {"score": 25.0 if lock else 0.0, "has_flake": False, "lockfile": lock}
            return

        try:
            text = flake.read_text(errors="ignore")
        except OSError:
            text = ""

        outputs = [k for k in ("packages", "devShells", "checks", "apps", "overlays", "nixosModules")
                   if re.search(rf"\b{k}\b\s*=", text)]

        wf_dir = repo_path / ".github" / "workflows"
        wf_blob = ""
        if wf_dir.is_dir():
            try:
                wf_blob = " ".join(p.read_text(errors="ignore").lower() for p in wf_dir.glob("*.y*ml"))
            except OSError:
                pass
        flake_check_ci = "nix flake check" in wf_blob
        test_in_ci = any(w in wf_blob for w in ("pytest", "cargo test", "npm test", "pnpm test", "go test", "nix flake check"))

        lock = repo_path / "flake.lock"
        lock_age_days = None
        if lock.exists():
            out = self._git_output(repo_path, ["log", "-1", "--format=%ct", "--", "flake.lock"]).strip()
            if out.isdigit():
                lock_age_days = int((datetime.now(UTC).timestamp() - int(out)) / 86400)

        score = 35.0                                   # having a flake at all
        score += min(30.0, len(outputs) * 6.0)         # what it actually exposes
        if flake_check_ci:
            score += 20.0
        if lock_age_days is not None and lock_age_days < 60:
            score += 15.0

        snapshot.reproducibility = {
            "score": round(min(100.0, score), 1),
            "has_flake": True,
            "outputs": outputs,
            "flake_check_in_ci": flake_check_ci,
            "test_in_ci": test_in_ci,
            "lock_age_days": lock_age_days,
        }

    def _collect_interface(self, repo_path: Path, snapshot: RepoMetricsSnapshot) -> None:
        """Delivered capability: endpoints, tools, modules, commands, crates."""
        counts = {"endpoints": 0, "mcp_tools": 0, "modules": 0, "cli_commands": 0, "workspace_members": 0}
        has_integration = False

        for f in self._iter_files(repo_path):
            rel = str(f.relative_to(repo_path))
            if "integration" in rel.lower() and SECURITY_ALLOWLIST.search(rel):
                has_integration = True
            ext = f.suffix.lower()
            if ext not in {".py", ".rs", ".ts", ".tsx", ".go", ".nix"}:
                continue
            try:
                text = f.read_text(errors="ignore")
            except (OSError, UnicodeDecodeError):
                continue
            counts["endpoints"] += len(re.findall(
                r'@(?:app|router)\.(?:get|post|put|delete|patch)\(|'
                r'\.route\(\s*["\']|HttpServer::|axum::Router', text))
            counts["cli_commands"] += len(re.findall(r'@(?:app|cli)\.command\(|#\[command\(', text))
            if rel.startswith(("src/tools/", "tools/")) and ext in {".ts", ".py"}:
                counts["mcp_tools"] += 1
            if ext == ".nix" and (rel.startswith("modules/") or "/modules/" in rel):
                counts["modules"] += 1

        cargo = repo_path / "Cargo.toml"
        if cargo.exists():
            try:
                counts["workspace_members"] = len(re.findall(
                    r'^\s*"[^"]+",', cargo.read_text(errors="ignore"), re.MULTILINE))
            except OSError:
                pass

        surface = (counts["endpoints"] + counts["mcp_tools"] * 2 + counts["modules"]
                   + counts["cli_commands"] + counts["workspace_members"] * 3)
        snapshot.interface = {
            "score": round(min(100.0, surface * 1.6), 1),
            "has_integration_tests": has_integration,
            **counts,
        }

    def _collect_operability(self, repo_path: Path, snapshot: RepoMetricsSnapshot) -> None:
        """Evidence the thing is actually operated, not merely built.

        Keeping ~28 services up, solo, is harder than writing any one of them; that
        work leaves traces (health probes, restart policies, structured logs, runbooks)
        and none of them were previously measured.
        """
        found: list[str] = []
        blob_parts: list[str] = []
        for name in ("Dockerfile", "docker-compose.yml", "docker-compose.yaml", "Makefile", "justfile"):
            p = repo_path / name
            if p.exists():
                try:
                    blob_parts.append(p.read_text(errors="ignore").lower())
                except OSError:
                    pass
        blob = " ".join(blob_parts)

        if "healthcheck" in blob:
            found.append("healthcheck")
        if "restart:" in blob or "restart=" in blob:
            found.append("restart_policy")
        if any((repo_path / n).exists() for n in ("RUNBOOK.md", "docs/RUNBOOK.md", "OPERATIONS.md")):
            found.append("runbook")

        src_blob = ""
        for f in self._iter_files(repo_path):
            if f.suffix.lower() not in {".py", ".rs", ".ts", ".go"}:
                continue
            try:
                src_blob += f.read_text(errors="ignore")[:4000].lower()
            except (OSError, UnicodeDecodeError):
                continue
            if len(src_blob) > 400_000:
                break

        if any(k in src_blob for k in ("structlog", "tracing::", "slog", "pino", "zap.", "logrus")):
            found.append("structured_logging")
        if any(k in src_blob for k in ("prometheus", "/metrics", "metrics_endpoint")):
            found.append("metrics_endpoint")
        if any(k in src_blob for k in ("opentelemetry", "jaeger", "tracer")):
            found.append("tracing")
        if any(k in src_blob for k in ("graceful", "shutdown_signal", "sigterm")):
            found.append("graceful_shutdown")
        if "/health" in src_blob or "健康" in src_blob:
            if "healthcheck" not in found:
                found.append("healthcheck")

        score = sum(OPERABILITY_MARKERS.get(m, 0.0) for m in found)
        snapshot.operability = {"score": round(min(100.0, score), 1), "signals": found}

    def _collect_knowledge(self, repo_path: Path, snapshot: RepoMetricsSnapshot) -> None:
        adr_count = 0
        for d in ("adr", "docs/adr", "decisions", "docs/decisions"):
            p = repo_path / d
            if p.is_dir():
                adr_count += len([f for f in p.rglob("*.md")])
        has_arch = (repo_path / "ARCHITECTURE.md").exists()
        has_readme = snapshot.has_readme
        diagrams = 0
        for d in ("docs", "diagrams", "docs/diagrams"):
            p = repo_path / d
            if p.is_dir():
                diagrams += len(list(p.rglob("*.mmd"))) + len(list(p.rglob("*.svg")))

        score = 0.0
        if has_readme:
            score += 20.0
        if has_arch:
            score += 25.0
        score += min(30.0, adr_count * 2.0)
        score += min(15.0, diagrams * 3.0)
        if snapshot.loc_docs > 2000:
            score += 10.0

        snapshot.knowledge = {
            "score": round(min(100.0, score), 1),
            "adr_count": adr_count,
            "has_architecture_md": has_arch,
            "diagrams": diagrams,
        }

    def _collect_adoption(self, repo_path: Path, snapshot: RepoMetricsSnapshot) -> None:
        """External validation. Only meaningful for repos the world can see."""
        remote = self._git_output(repo_path, ["remote", "get-url", "origin"]).strip()
        meta = self._github_meta().get(repo_path.name, {})
        snapshot.is_public = bool(meta) or bool(meta.get("public")) if meta else False

        if not snapshot.is_public:
            snapshot.adoption = {
                "score": None,
                "reason": "private or unpublished — adoption not observable",
                "remote": bool(remote),
            }
            return

        stars = int(meta.get("stars", 0) or 0)
        forks = int(meta.get("forks", 0) or 0)
        contributors = max(0, snapshot.git.get("contributors", 0) - 1)

        score = min(60.0, stars * 3.0) + min(25.0, forks * 5.0) + min(15.0, contributors * 5.0)
        snapshot.adoption = {
            "score": round(min(100.0, score), 1),
            "stars": stars,
            "forks": forks,
            "external_contributors": contributors,
        }

    def _github_meta(self) -> dict[str, Any]:
        """Star/fork counts collected at build time by the portfolio site."""
        if self._gh_meta_cache is not None:
            return self._gh_meta_cache
        self._gh_meta_cache = {}
        candidate = self.arch_path / "projects-gui" / "portfolio" / "public" / "github-meta.json"
        if candidate.exists():
            try:
                raw = json.loads(candidate.read_text())
                repos = raw.get("repos", raw) if isinstance(raw, dict) else raw
                if isinstance(repos, dict):
                    self._gh_meta_cache = repos
                elif isinstance(repos, list):
                    self._gh_meta_cache = {r.get("name"): r for r in repos if isinstance(r, dict)}
            except Exception:
                pass
        return self._gh_meta_cache

    def _classify(self, repo_path: Path, snapshot: RepoMetricsSnapshot) -> None:
        filenames = {p.name for p in repo_path.iterdir()} if repo_path.is_dir() else set()
        archetype = classify_archetype(
            repo_path.name,
            deps=snapshot.dependencies,
            loc_authored=snapshot.loc_authored,
            loc_docs=snapshot.loc_docs,
            filenames=filenames,
            has_dockerfile="Dockerfile" in filenames,
            primary_language=snapshot.primary_language,
            total_commits=snapshot.git.get("total_commits", 0),
            has_ci=snapshot.has_ci,
            tags=snapshot.git.get("tags", 0),
            # Workspace/Cargo deps are often not parseable, so fall back to what the
            # source actually does: a repo serving HTTP routes is a service.
            endpoints=snapshot.interface.get("endpoints", 0),
            modules=snapshot.interface.get("modules", 0),
            cli_commands=snapshot.interface.get("cli_commands", 0),
        )
        snapshot.archetype = archetype.value
        snapshot.stack_layer = classify_layer(repo_path.name, archetype).value

    def _calculate_health(self, snapshot: RepoMetricsSnapshot) -> HealthResult:
        """Profile-weighted score over the dimensions that apply to this archetype.

        `None` means the dimension does not apply and is excluded from the weighted
        mean — as opposed to 0.0, which means it applies and the repo scores badly.
        Collapsing those two is what made a docs site look like a broken service.
        """
        archetype = Archetype(snapshot.archetype)
        layer = StackLayer(snapshot.stack_layer)

        dims: dict[Dimension, float | None] = {
            Dimension.CENTRALITY: snapshot.centrality_score,
            Dimension.SUSTAINED_DELIVERY: snapshot.delivery.get("score"),
            Dimension.RELEASE_DISCIPLINE: snapshot.release.get("score"),
            Dimension.REPRODUCIBILITY: snapshot.reproducibility.get("score"),
            Dimension.INTERFACE_SURFACE: snapshot.interface.get("score"),
            Dimension.TEST_DEPTH: self._test_depth_score(snapshot),
            Dimension.SECURITY_POSTURE: snapshot.security_score,
            Dimension.OPERABILITY: snapshot.operability.get("score"),
            Dimension.ARCHITECTURE_DEPTH: self._architecture_score(snapshot),
            Dimension.KNOWLEDGE_ARTIFACTS: snapshot.knowledge.get("score"),
            # A private repo has no observable stars or forks. That is a publishing
            # decision, not a quality signal, so it is N/A rather than zero.
            Dimension.ADOPTION: snapshot.adoption.get("score") if snapshot.is_public else None,
        }
        return score_repo(archetype, layer, dims)

    def _test_depth_score(self, snapshot: RepoMetricsSnapshot) -> float | None:
        """Ratio and kind of tests, not raw file count."""
        if snapshot.loc_authored < 200:
            return None  # too small for the ratio to mean anything
        if not snapshot.has_tests:
            return 0.0
        score = 0.0
        ratio = snapshot.test_files / max(1, snapshot.total_files)
        score += min(50.0, ratio * 250.0)
        if snapshot.interface.get("has_integration_tests"):
            score += 25.0
        if snapshot.reproducibility.get("test_in_ci"):
            score += 25.0
        return round(min(100.0, score), 1)

    @staticmethod
    def _architecture_score(snapshot: RepoMetricsSnapshot) -> float | None:
        score = 0.0
        if snapshot.knowledge.get("has_architecture_md"):
            score += 30.0
        modules = snapshot.interface.get("modules", 0)
        score += min(30.0, modules * 1.5)
        score += min(20.0, snapshot.max_depth * 3.0)
        if snapshot.knowledge.get("adr_count", 0) > 0:
            score += 20.0
        return round(min(100.0, score), 1)

    @staticmethod
    def _determine_status(snapshot: RepoMetricsSnapshot) -> str:
        """Lifecycle, not recency.

        A finished, tagged, reproducible repo with no commits this quarter is *stable*,
        not archived. The old mapping treated silence as decay, which is why mature
        work ranked below whatever happened to be touched last week.
        """
        git = snapshot.git
        total = git.get("total_commits", 0)
        if total == 0:
            return "empty"
        if git.get("commits_30d", 0) > 0:
            return "active"
        if git.get("commits_90d", 0) > 0:
            return "maintenance"
        # Released and reproducible => deliberately finished.
        if git.get("tags", 0) > 0 and snapshot.has_ci:
            return "stable"
        return "dormant"

    # ------------------------------------------------------------------
    # Git helpers
    # ------------------------------------------------------------------
    @staticmethod
    def _git_output(repo_path: Path, args: list[str]) -> str:
        try:
            r = subprocess.run(
                ["git", *args], cwd=repo_path,
                capture_output=True, text=True, timeout=15,
            )
            return r.stdout if r.returncode == 0 else ""
        except (subprocess.TimeoutExpired, OSError):
            return ""

    @classmethod
    def _git_int(cls, repo_path: Path, args: list[str]) -> int:
        try:
            return int(cls._git_output(repo_path, args).strip())
        except ValueError:
            return 0

    def get_head_hash(self, repo_path: Path) -> str:
        return self._git_output(repo_path, ["rev-parse", "HEAD"]).strip()

    # ------------------------------------------------------------------
    # Persistence
    # ------------------------------------------------------------------
    def _save_snapshot(self, snapshots: list[RepoMetricsSnapshot]) -> None:
        now = datetime.now(UTC)
        data = {
            "generated_at": now.isoformat(),
            "repo_count": len(snapshots),
            "repos": [snap.to_dict() for snap in snapshots],
        }
        
        # Save timestamped history
        history_dir = self.metrics_dir / "history"
        history_dir.mkdir(exist_ok=True)
        timestamp = now.strftime("%Y%m%d_%H%M%S")
        (history_dir / f"metrics_snapshot_{timestamp}.json").write_text(json.dumps(data, indent=2))
        
        # Save latest
        (self.metrics_dir / "metrics_snapshot.json").write_text(json.dumps(data, indent=2))
        logger.info("Saved metrics snapshot: %d repos", len(snapshots))

    def load_snapshot(self) -> dict[str, Any] | None:
        p = self.metrics_dir / "metrics_snapshot.json"
        if not p.exists():
            return None
        try:
            return json.loads(p.read_text())
        except Exception:
            return None
