@dataclass
class RepoMetricsSnapshot:
    """Full metrics snapshot for one repository."""

    name: str
    path: str
    collected_at: str = ""

    # code
    total_files: int = 0
    total_loc: int = 0          # authored only — see loc_* buckets below
    languages: dict[str, dict[str, int]] = field(default_factory=dict)
    primary_language: str = ""

    # LoC buckets (concept A: measurement). total_loc == loc_authored; the rest are
    # reported separately so vendored deps never inflate an authorship claim.
    loc_authored: int = 0
    loc_vendored: int = 0
    loc_generated: int = 0
    loc_docs: int = 0
    loc_config: int = 0

    # classification (concepts B + C)
    archetype: str = "unknown"
    stack_layer: str = "unknown"

    # git
    git: dict[str, Any] = field(default_factory=dict)

    # deps
    dependencies: list[str] = field(default_factory=list)
    dep_count: int = 0

    # security
    security_findings: list[dict[str, Any]] = field(default_factory=list)
    security_score: float = 100.0

    # quality
    has_tests: bool = False
    test_files: int = 0
    has_ci: bool = False
    has_readme: bool = False
    has_docs: bool = False
    has_flake: bool = False

    # architecture (new)
    frameworks: list[str] = field(default_factory=list)
    entrypoints: list[str] = field(default_factory=list)
    infrastructure: list[str] = field(default_factory=list)
    databases: list[str] = field(default_factory=list)
    apis: list[str] = field(default_factory=list)
    
    # complexity (new)
    max_depth: int = 0
    avg_file_size: int = 0
    largest_files: list[dict[str, Any]] = field(default_factory=list)

    # signals feeding the rubric (concept D)
    release: dict[str, Any] = field(default_factory=dict)
    reproducibility: dict[str, Any] = field(default_factory=dict)
    interface: dict[str, Any] = field(default_factory=dict)
    operability: dict[str, Any] = field(default_factory=dict)
    security_posture: dict[str, Any] = field(default_factory=dict)
    knowledge: dict[str, Any] = field(default_factory=dict)
    delivery: dict[str, Any] = field(default_factory=dict)

    # visibility — a private repo has no observable adoption. That is a publishing
    # decision, not a quality signal, so adoption is scored N/A rather than zero.
    is_public: bool = False
    adoption: dict[str, Any] = field(default_factory=dict)

    # centrality is cross-repo, so it is filled in a second pass over all snapshots
    dependents: list[str] = field(default_factory=list)
    centrality_score: float | None = None

    # derived
    health_score: float = 0.0
    health: dict[str, Any] = field(default_factory=dict)
    status: str = "unknown"

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


# ---------------------------------------------------------------------------
# Collector
# ---------------------------------------------------------------------------
class MetricsCollector:
    """Zero-token metrics collector.  git + fs + regex, no LLM."""

    def __init__(self, arch_path: str | None = None):
        self.arch_path = Path(arch_path or os.getenv("CEREBRO_ARCH_PATH", str(Path.home() / "master")))
        self.metrics_dir = self.arch_path / "cerebro" / "data" / "metrics"
        self.metrics_dir.mkdir(parents=True, exist_ok=True)
        self._gh_meta_cache: dict[str, Any] | None = None

    # ------------------------------------------------------------------
    # Discovery
    # ------------------------------------------------------------------
    # Names that are vendor / skill sub-repos — skip them
    SKIP_REPO_NAMES = {"ux-agents", "forge-std", "sdk-core"}

    def discover_repos(self) -> list[Path]:
        """Discover git repos up to 2 levels deep under arch_path, deduplicated."""
        seen: set = set()          # resolved paths already added
        repos: list[Path] = []
        skip_top = {"scripts", "docs", "skills"}

        def _add(p: Path) -> None:
            resolved = p.resolve()
            if resolved in seen or p.name in self.SKIP_REPO_NAMES:
                return
            seen.add(resolved)
            repos.append(p)

        for top in sorted(self.arch_path.iterdir()):
            if not top.is_dir() or top.name.startswith(".") or top.name in skip_top:
                continue
            if (top / ".git").exists():
                _add(top)

            try:
                for sub in sorted(top.iterdir()):
                    if not sub.is_dir() or sub.name.startswith(".") or sub.name in SKIP_DIRS:
                        continue
                    if (sub / ".git").exists():
                        _add(sub)
                    # two levels deep (e.g. org/repo/services/*)
                    try:
                        for subsub in sorted(sub.iterdir()):
                            if not subsub.is_dir() or subsub.name.startswith(".") or subsub.name in SKIP_DIRS:
                                continue
                            if (subsub / ".git").exists():
                                _add(subsub)
                    except (PermissionError, OSError):
                        pass
            except (PermissionError, OSError):
                pass

        return repos

    # ------------------------------------------------------------------
    # Bulk / single collection
    # ------------------------------------------------------------------
    def collect_all(self) -> list[RepoMetricsSnapshot]:
        repos = self.discover_repos()
        logger.info("MetricsCollector: discovered %d repos", len(repos))
        results: list[RepoMetricsSnapshot] = []
        for repo_path in repos:
            try:
                results.append(self.collect_repo(repo_path))
            except Exception as e:
                logger.error("  ✗ %s: %s", repo_path.name, e)

        # Second pass: centrality is a property of the graph, not of a single repo.
        self._score_centrality(results)
        for snapshot in results:
            health = self._calculate_health(snapshot)
            snapshot.health = health.to_dict()
            snapshot.health_score = health.score
            logger.info(
                "  ✓ %-22s %-16s LoC=%-7d health=%.0f",
                snapshot.name, snapshot.archetype, snapshot.total_loc, snapshot.health_score,
            )

        self._save_snapshot(results)
        return results

    def collect_repo(self, repo_path: Path) -> RepoMetricsSnapshot:
        snapshot = RepoMetricsSnapshot(
            name=repo_path.name,
            path=str(repo_path),
            collected_at=datetime.now(UTC).isoformat(),
        )
        self._collect_code_metrics(repo_path, snapshot)
        self._collect_git_metrics(repo_path, snapshot)
        self._collect_dependencies(repo_path, snapshot)
        self._collect_quality(repo_path, snapshot)
        self._collect_security(repo_path, snapshot)
        self._collect_architecture(repo_path, snapshot)
        self._collect_interface(repo_path, snapshot)

        # Classification must run after code/git/deps/interface so it can see their
        # signals, and before scoring, which is weighted by the resulting profile.
        self._classify(repo_path, snapshot)

        self._collect_delivery(repo_path, snapshot)
        self._collect_release(repo_path, snapshot)
        self._collect_reproducibility(repo_path, snapshot)
        self._collect_operability(repo_path, snapshot)
        self._collect_knowledge(repo_path, snapshot)
        self._collect_adoption(repo_path, snapshot)

        snapshot.status = self._determine_status(snapshot)

        # Provisional score so single-repo callers (watcher, `metrics report`) get a
        # usable number. collect_all() recomputes it once centrality is known; until
        # then centrality is None, i.e. N/A rather than a zero.
        health = self._calculate_health(snapshot)
        snapshot.health = health.to_dict()
        snapshot.health_score = health.score
        return snapshot

    # ------------------------------------------------------------------
    # Centrality — cross-repo, so it needs every snapshot to exist first
    # ------------------------------------------------------------------
    def _score_centrality(self, snapshots: list[RepoMetricsSnapshot]) -> None:
        """Blast radius: how much of the ecosystem leans on this repo.

        This is the clearest seniority signal in the whole rubric and was entirely
        unmeasured — owning the component 28 services depend on is a different kind
        of work from owning a leaf.
        """
        names = {s.name for s in snapshots}
        dependents: dict[str, set[str]] = {n: set() for n in names}

        # Orchestration: a service named in the master compose is depended upon.
        compose_refs: set[str] = set()
        for compose in (
            self.arch_path / "deploy" / "docker-compose.master.yml",
            Path.home() / "Projects" / "master" / "deploy" / "docker-compose.master.yml",
        ):
            if compose.exists():
                try:
                    blob = compose.read_text(errors="ignore")
                    compose_refs |= {n for n in names if re.search(rf'\b{re.escape(n)}\b', blob)}
                except OSError:
                    pass

        for snap in snapshots:
            src = Path(snap.path)
            # A flake *input* pointing at a sibling repo is a hard dependency edge.
            # Matching the bare name anywhere in the file is far too loose: it makes
            # `nixos-hardware` an edge to `nixos` and `cerebro-reranker` an edge to
            # `cerebro`, which flattened five unrelated repos to a perfect score.
            flake = src / "flake.nix"
            if not flake.exists():
                continue
            try:
                text = flake.read_text(errors="ignore")
            except OSError:
                continue

            referenced: set[str] = set()
            for m in re.finditer(r'url\s*=\s*"([^"]+)"', text):
                url = m.group(1)
                tail = url.rstrip("/").split("/")[-1].split("?")[0]
                if tail in names:
                    referenced.add(tail)
            for other in referenced:
                if other != snap.name:
                    dependents[other].add(snap.name)

        for snap in snapshots:
            deps = dependents[snap.name]
            score = min(70.0, len(deps) * 14.0)
            if snap.name in compose_refs:
                score += 30.0  # part of the integrated platform, not a standalone repo
            snap.dependents = sorted(deps)
            snap.centrality_score = round(min(100.0, score), 1)

    # ------------------------------------------------------------------
    # Code metrics (filesystem)
    # ------------------------------------------------------------------
    @staticmethod
    def _bucket_for(rel_parts: tuple[str, ...], ext: str) -> str:
        """Classify a file into an LoC bucket (concept A).

        Order matters: vendored and generated win over language, because a vendored
        Go file is a dependency regardless of it being Go.
        """
        if any(p in VENDOR_DIRS for p in rel_parts):
            return "vendored"
        if any(p in GENERATED_DIRS for p in rel_parts) or GENERATED_FILES.search("/".join(rel_parts)):
            return "generated"
        if ext in DOC_EXTS:
            return "docs"
        if ext in CONFIG_EXTS:
            return "config"
        return "authored"

    def _collect_code_metrics(self, repo_path: Path, snapshot: RepoMetricsSnapshot) -> None:
        lang_stats: dict[str, dict[str, int]] = defaultdict(lambda: {"files": 0, "lines": 0})
        buckets: dict[str, int] = defaultdict(int)

        for file_path in self._iter_files(repo_path):
            if snapshot.total_files >= MAX_FILES_PER_REPO:
                break
            snapshot.total_files += 1
            ext = file_path.suffix.lower()
            try:
                rel_parts = file_path.relative_to(repo_path).parts
            except ValueError:
                continue

            # Only count text we can actually attribute. Reading a .png with
            # errors="ignore" and calling splitlines() yields tens of thousands of
            # "lines" of decoded binary — that alone accounted for 119K of the wiki's
            # supposed 123K authored lines.
            if ext not in KNOWN_TEXT_EXTS:
                continue

            bucket = self._bucket_for(rel_parts, ext)
            try:
                lines = len(file_path.read_text(errors="ignore").splitlines())
            except (OSError, UnicodeDecodeError):
                continue
            buckets[bucket] += lines

            # Language stats describe authored code only. Counting vendored Go as the
            # repo's primary language is how owasaka came out as a 1.36M-line Go project.
            if bucket == "authored" and ext in EXT_TO_LANG:
                lang = EXT_TO_LANG[ext]
                lang_stats[lang]["files"] += 1
                lang_stats[lang]["lines"] += lines

        snapshot.loc_authored = buckets["authored"]
        snapshot.loc_vendored = buckets["vendored"]
        snapshot.loc_generated = buckets["generated"]
        snapshot.loc_docs = buckets["docs"]
        snapshot.loc_config = buckets["config"]
        snapshot.total_loc = buckets["authored"]

        snapshot.languages = dict(lang_stats)
        if lang_stats:
            snapshot.primary_language = max(lang_stats, key=lambda k: lang_stats[k]["lines"])

    def _iter_files(self, path: Path, depth: int = 0) -> Iterator[Path]:
        """Enumerate repo files, preferring git's index over a filesystem walk.

        `git ls-files` gives exactly the tracked set, which excludes everything
        .gitignore already handles (build output, virtualenvs, node_modules) without
        needing to guess at directory names. Falls back to walking for non-git dirs.
        """
        if depth == 0 and (path / ".git").exists():
            tracked = self._git_output(path, ["ls-files", "-z"])
            if tracked:
                for rel in tracked.split("\0"):
                    if not rel:
                        continue
                    parts = Path(rel).parts
                    if any(p in SKIP_DIRS for p in parts):
                        continue
                    f = path / rel
                    try:
                        if f.is_file() and f.stat().st_size < 5_000_000:
                            yield f
                    except OSError:
                        continue
                return

        if depth > 7:
            return
        try:
            for item in path.iterdir():
                if item.name.startswith(".") or item.name in SKIP_DIRS:
                    continue
                if item.is_file():
                    try:
                        if item.stat().st_size < 5_000_000:  # skip files > 5 MB
                            yield item
                    except OSError:
                        pass
                elif item.is_dir():
                    yield from self._iter_files(item, depth + 1)
        except PermissionError:
            pass

    # ------------------------------------------------------------------
    # Git metrics
    # ------------------------------------------------------------------
    def _collect_git_metrics(self, repo_path: Path, snapshot: RepoMetricsSnapshot) -> None:
        if not (repo_path / ".git").exists():
            snapshot.git = {"error": "not a git repo"}
            return

        git: dict[str, Any] = {}
        git["total_commits"] = self._git_int(repo_path, ["rev-list", "--count", "HEAD"])
        git["commits_30d"] = self._git_int(repo_path, ["rev-list", "--count", "--after=30 days ago", "HEAD"])
        git["commits_90d"] = self._git_int(repo_path, ["rev-list", "--count", "--after=90 days ago", "HEAD"])

        # contributors
        shortlog = self._git_output(repo_path, ["shortlog", "-sn", "--no-merges"])
        git["contributors"] = len([ln for ln in shortlog.splitlines() if ln.strip()])

        # branches / tags
        git["branches"] = len([ln for ln in self._git_output(repo_path, ["branch", "--list"]).splitlines() if ln.strip()])
        git["tags"] = len([ln for ln in self._git_output(repo_path, ["tag", "--list"]).splitlines() if ln.strip()])

        # last commit info
        last = self._git_output(repo_path, ["log", "-1", "--format=%H|%an|%ai|%s"])
        if last and "|" in last:
            parts = last.strip().split("|", 3)
            if len(parts) >= 4:
                git["last_commit_hash"] = parts[0][:12]
                git["last_commit_author"] = parts[1]
                git["last_commit_date"] = parts[2]
                git["last_commit_message"] = parts[3][:120]

        # top contributors
        git["top_contributors"] = []
        for line in shortlog.splitlines()[:5]:
            m = re.match(r"\s*(\d+)\s+(.+)", line.strip())
            if m:
                git["top_contributors"].append({"name": m.group(2).strip(), "commits": int(m.group(1))})

        snapshot.git = git

    # ------------------------------------------------------------------
    # Dependencies
    # ------------------------------------------------------------------
    def _collect_dependencies(self, repo_path: Path, snapshot: RepoMetricsSnapshot) -> None:
        deps: list[str] = []

        # pyproject.toml (Poetry)
        pyproject = repo_path / "pyproject.toml"
        if pyproject.exists():
            try:
                data = tomllib.loads(pyproject.read_text())
                for name in data.get("tool", {}).get("poetry", {}).get("dependencies", {}):
                    if name != "python":
                        deps.append(f"py:{name}")
            except Exception:
                pass

        # package.json
        pkg = repo_path / "package.json"
        if pkg.exists():
            try:
                data = json.loads(pkg.read_text())
                for name in data.get("dependencies", {}):
                    deps.append(f"npm:{name}")
                for name in data.get("devDependencies", {}):
                    deps.append(f"npm-dev:{name}")
            except Exception:
                pass

        # Cargo.toml
        cargo = repo_path / "Cargo.toml"
        if cargo.exists():
            try:
                content = cargo.read_text()
                in_deps = False
                for line in content.splitlines():
                    stripped = line.strip()
                    if stripped == "[dependencies]":
                        in_deps = True
                        continue
                    if stripped.startswith("[") and in_deps:
                        break
                    if in_deps:
                        m = re.match(r'^([\w-]+)\s*=', stripped)
                        if m:
                            deps.append(f"cargo:{m.group(1)}")
            except Exception:
                pass

        # go.mod
        gomod = repo_path / "go.mod"
        if gomod.exists():
            try:
                in_require = False
                for line in gomod.read_text().splitlines():
                    stripped = line.strip()
                    if stripped.startswith("require"):
                        in_require = True
                        continue
                    if in_require and stripped == ")":
                        in_require = False
                        continue
                    if in_require:
                        m = re.match(r"([\w./\-]+)\s+v", stripped)
                        if m:
                            deps.append(f"go:{m.group(1)}")
            except Exception:
                pass

        snapshot.dependencies = deps
        snapshot.dep_count = len(deps)

    # ------------------------------------------------------------------
    # Security scan
    # ------------------------------------------------------------------
    @staticmethod
    def _shannon_entropy(s: str) -> float:
        if not s:
            return 0.0
        counts = Counter(s)
        n = len(s)
        return -sum((c / n) * math.log2(c / n) for c in counts.values())

    def _collect_security(self, repo_path: Path, snapshot: RepoMetricsSnapshot) -> None:
        """Security posture = positive hardening evidence, minus *credible* findings.

        The previous model was `100 - hits * 10` over a regex that matched any field
        literally named `api_key`. That inverted the signal: securellm-mcp scored 0
        because it declares 62 tool schemas, and nixos scored 10 because it ships 294
        hardening modules that name the things they harden. Findings now require an
        entropy gate and skip fixture/schema/example paths, and posture is driven by
        what the repo actively does — SECURITY.md, sops, signing chains, SBOM, OPA.
        """
        findings: list[dict[str, Any]] = []
        scanned = 0
        tooling: set[str] = set()

        for file_path in self._iter_files(repo_path):
            if scanned >= 15_000:
                break
            ext = file_path.suffix.lower()
            rel = str(file_path.relative_to(repo_path))

            # Configuring a security tool is hardening evidence, wherever it lives.
            low_rel = rel.lower()
            tooling |= {t for t in SECURITY_TOOLING if t in low_rel}

            applicable = {n: p for n, (p, exts) in SECURITY_PATTERNS.items() if ext in exts}
            if not applicable or SECURITY_ALLOWLIST.search(rel):
                continue
            scanned += 1
            try:
                content = file_path.read_text(errors="ignore")
            except (OSError, UnicodeDecodeError):
                continue

            for pname, pat in applicable.items():
                m = pat.search(content)
                if not m:
                    continue
                # For secret-shaped matches, require the literal to actually look random.
                if pname == "hardcoded_secret":
                    literal = m.group(2) if m.lastindex and m.lastindex >= 2 else ""
                    if self._shannon_entropy(literal) < SECRET_ENTROPY_MIN:
                        continue
                findings.append({
                    "type": pname,
                    "file": rel,
                    "line": content[: m.start()].count("\n") + 1,
                })

        # Positive posture signals
        posture: dict[str, Any] = {"signals": [], "points": 0.0}
        for fname, pts in SECURITY_POSTURE_FILES.items():
            if (repo_path / fname).exists():
                posture["signals"].append(fname)
                posture["points"] += pts
        for dname, pts in SECURITY_POSTURE_DIRS.items():
            if (repo_path / dname).is_dir():
                posture["signals"].append(f"{dname}/")
                posture["points"] += pts
        if tooling:
            posture["signals"].extend(sorted(tooling))
            posture["points"] += min(30.0, len(tooling) * 6.0)
            posture["tooling"] = sorted(tooling)

        # Supply-chain evidence lives in CI, not at the repo root.
        wf_dir = repo_path / ".github" / "workflows"
        if wf_dir.is_dir():
            try:
                wf_blob = " ".join(
                    p.read_text(errors="ignore").lower()
                    for p in wf_dir.glob("*.y*ml")
                )
            except OSError:
                wf_blob = ""
            for needle, label, pts in (
                ("gitleaks", "secret-scan", 10.0),
                ("trufflehog", "secret-scan", 10.0),
                ("syft", "sbom", 10.0),
                ("cyclonedx", "sbom", 10.0),
                ("cosign", "artifact-signing", 10.0),
                ("trivy", "cve-scan", 8.0),
                ("semgrep", "sast", 8.0),
                ("lynis", "hardening-audit", 12.0),
            ):
                if needle in wf_blob and label not in posture["signals"]:
                    posture["signals"].append(label)
                    posture["points"] += pts

        posture["findings"] = len(findings)
        snapshot.security_findings = findings
        snapshot.security_posture = posture
        # Baseline 45 so a repo with no explicit posture is "unproven", not "insecure".
        snapshot.security_score = round(
            max(0.0, min(100.0, 45.0 + posture["points"] - len(findings) * 6.0)), 1
        )

