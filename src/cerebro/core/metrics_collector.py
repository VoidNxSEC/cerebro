    def _collect_quality(self, repo_path: Path, snapshot: RepoMetricsSnapshot) -> None:
        snapshot.has_readme = any((repo_path / f).exists() for f in ["README.md", "README.rst", "README"])
        snapshot.has_docs = (repo_path / "docs").exists()
        snapshot.has_flake = (repo_path / "flake.nix").exists()
        snapshot.has_ci = (
            (repo_path / ".github" / "workflows").exists()
            or (repo_path / ".gitlab-ci.yml").exists()
            or (repo_path / "Jenkinsfile").exists()
        )

        # Tests are counted wherever they live. Requiring a top-level tests/ directory
        # missed every co-located suite (`Foo.test.ts`, `foo_test.go`, `#[cfg(test)]`),
        # which read as "no tests at all" for repos that are in fact well covered.
        count = 0
        for f in self._iter_files(repo_path):
            rel = f.relative_to(repo_path).as_posix()
            if re.search(r'(^|/)(tests?|__tests__|spec)(/|$)', rel) or \
               re.search(r'(^|/)test_[^/]+$|_test\.[a-z]+$|\.test\.[a-z]+$|\.spec\.[a-z]+$', rel):
                count += 1
                if count >= 5000:
                    break

        snapshot.test_files = count
        snapshot.has_tests = count > 0

